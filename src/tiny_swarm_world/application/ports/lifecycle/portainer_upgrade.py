"""Portainer management lifecycle and durable recovery boundaries."""
from contextlib import AbstractContextManager
from typing import Protocol

from tiny_swarm_world.domain.lifecycle.portainer_upgrade import PortainerCheckpoint, PortainerObservation


class PortainerUpgradeRuntime(Protocol):
    async def inspect(self) -> PortainerObservation: ...
    async def backup(self, checkpoint: PortainerCheckpoint) -> str: ...
    async def upgrade(self, checkpoint: PortainerCheckpoint) -> None: ...
    async def cancel_backup(self, checkpoint: PortainerCheckpoint) -> None: ...
    async def restore(self, checkpoint: PortainerCheckpoint) -> None: ...
    async def verify(self, before: PortainerObservation, *, recovery: bool) -> None: ...


class PortainerUpgradeJournal(Protocol):
    def exclusive(self) -> AbstractContextManager[None]: ...
    def load(self) -> PortainerCheckpoint | None: ...
    def save(self, checkpoint: PortainerCheckpoint) -> None: ...
