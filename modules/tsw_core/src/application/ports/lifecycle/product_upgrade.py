"""Product release, durable progress and installed-selection verification ports."""
from contextlib import AbstractContextManager
from typing import Protocol

from tiny_swarm_world.domain.lifecycle.models import InstallationManifest
from tiny_swarm_world.domain.lifecycle.product_upgrade import ProductCheckpoint, ProductPlan


class ProductUpgradeJournal(Protocol):
    def exclusive(self) -> AbstractContextManager: ...
    def load(self) -> ProductCheckpoint | None: ...
    def save(self, checkpoint: ProductCheckpoint) -> None: ...


class ProductInstallation(Protocol):
    def plan(self, target: str) -> ProductPlan: ...
    def validate(self, plan: ProductPlan) -> None: ...
    def stage(self, plan: ProductPlan) -> None: ...
    def migrate(self, plan: ProductPlan) -> None: ...
    def activate(self, plan: ProductPlan) -> None: ...
    def verify_product(self, plan: ProductPlan) -> None: ...
    def verify_target_runtime(self, plan: ProductPlan) -> None: ...
    def verify_active(self, plan: ProductPlan) -> None: ...


class ProductRuntime(Protocol):
    async def verify(self, manifest: InstallationManifest, *, plan: ProductPlan | None = None) -> dict[str, str]: ...
